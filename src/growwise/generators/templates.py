def variants_for(kind: MaterialKind, stage: Stage) -> tuple[str, ...]:
    """Return the raw body templates (with the ``{topic}`` token) for a kind at a stage."""
    pool = _INFANT if stage is Stage.INFANT_0_2 else _GENERAL
    return pool[kind]


def variant_index(topic: str, stage: Stage, count: int) -> int:
    """Deterministic variant index from a stable topic+stage hash (never random, never time)."""
    key = f"{topic}\x1f{stage.value}".encode()
    digest = hashlib.sha256(key).digest()
    return int.from_bytes(digest[:8], "big") % count


def select_body(*, kind: MaterialKind, topic: str, stage: Stage) -> str:
    """Choose one stage-appropriate scaffolded body deterministically and fill in the topic."""
    variants = variants_for(kind, stage)
    body = variants[variant_index(topic, stage, len(variants))]
    return body.replace(_TOPIC_TOKEN, topic)
