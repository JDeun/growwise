# Deterministic template library.
#
# Each MaterialKind draws from several stage-appropriate body variants. The variant is chosen by a
# stable hash of ``topic`` + ``stage`` so the same request always yields the same body (never
# random, never time based). Every variant stays scaffolded (staged hints, no final answers, no
# rote pressure) and observation oriented so parent-facing drafts keep passing ScaffoldGuard.
#
# Infants (INFANT_0_2) and preschoolers (PRESCHOOL_3_5) draw from developmentally distinct,
# parent-supported play/observation pools. Elementary learners use the concrete-to-representation
# general pool. Middle/high learners use an evidence/reasoning-oriented secondary pool. The
# ``{topic}`` token is substituted verbatim, so topic content is treated as data and never
# re-parsed as a format string.

_TOPIC_TOKEN = "{topic}"


