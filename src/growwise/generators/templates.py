# Deterministic template library.
#
# Each MaterialKind draws from several stage-appropriate body variants. The variant is chosen by a
# stable hash of ``topic`` + ``stage`` so the same request always yields the same body (never
# random, never time based). Every variant stays scaffolded (staged hints, no final answers, no
# rote pressure) and observation oriented so parent-facing drafts keep passing ScaffoldGuard.
#
# Infants (INFANT_0_2) draw from a separate, parent-facing play/observation pool -- no worksheets,
# no "get it right" pressure -- while older stages share the general pool. The ``{topic}`` token is
# substituted verbatim, so topic content is treated as data and never re-parsed as a format string.

